"""Build AmlanAcharya_Capstone_Submission.zip in the layout required by the Submission Guide.

Usage: python scripts/package_submission.py [--video path/to/AmlanAcharya_Capstone_Video.mp4]

01_Video      the final Clipchamp export if --video is given, otherwise the HyperFrames film + in-app demo
              (the webcam intro/outro cannot be generated by code and must be added in Clipchamp)
02_Report     the PDF report
03_Workbooks  five stage workbooks + effort log
04_Source_Code  tracked + untracked-but-not-ignored files, plus .git history; never .env or caches
"""
import argparse
import subprocess
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAME = "AmlanAcharya"
OUT = ROOT / "04_Submission" / f"{NAME}_Capstone_Submission.zip"
SKIP_PREFIX = ("hyperframes_film/renders/", "hyperframes_film/.hyperframes/", "01_Video/", "04_Submission/")
SKIP_SUFFIX = (".mp4",)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--video")
    args = ap.parse_args()

    files = subprocess.run(["git", "ls-files", "-co", "--exclude-standard"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.splitlines()
    files = [f for f in files if not f.startswith(SKIP_PREFIX) and not f.endswith(SKIP_SUFFIX) and Path(ROOT, f).is_file()]
    assert not any(f == ".env" or f.endswith("/.env") for f in files), "refusing to package .env"

    OUT.parent.mkdir(exist_ok=True)
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
        if args.video:
            z.write(args.video, f"01_Video/{NAME}_Capstone_Video.mp4")
            demo = ROOT / "01_Video" / "in_app_demo_live_voiced.mp4"
            z.write(demo if demo.exists() else ROOT / "01_Video" / "in_app_demo_live.mp4", f"01_Video/{NAME}_In_App_Demo.mp4")
        else:
            film = sorted((ROOT / "hyperframes_film" / "renders").glob("film_*.mp4"))
            if film:
                z.write(film[-1], f"01_Video/{NAME}_HyperFrames_Film_NO_WEBCAM.mp4")
            z.write(ROOT / "01_Video" / "in_app_demo_live.mp4", "01_Video/in_app_demo_live.mp4")
            z.writestr("01_Video/README.txt", "Webcam intro/outro not yet added. Replace these files with the final Clipchamp export named "
                       f"{NAME}_Capstone_Video.mp4 (about 20 minutes, 1080p, you on camera at the start and end).\n")
        z.write(ROOT / "02_Report" / f"{NAME}_Capstone_Report.pdf", f"02_Report/{NAME}_Capstone_Report.pdf")
        for wb in sorted((ROOT / "03_Workbooks").glob("*.docx")):
            z.write(wb, f"03_Workbooks/{wb.name}")
        for f in files:
            z.write(ROOT / f, f"04_Source_Code/{f}")
        git_dir = ROOT / ".git"
        for p in git_dir.rglob("*"):
            if p.is_file():
                z.write(p, f"04_Source_Code/.git/{p.relative_to(git_dir).as_posix()}")
    print(OUT, f"{OUT.stat().st_size / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
